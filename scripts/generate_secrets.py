#!/usr/bin/env python3
import os
import plistlib
import sys

# Determine SRCROOT (Root directory of the project)
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SRCROOT = os.path.dirname(SCRIPT_DIR)
SRCROOT = os.environ.get("SRCROOT", DEFAULT_SRCROOT)

SECRETS_PLIST_ENV = os.environ.get("SECRETS_PLIST_PATH")

candidate_paths = []
if SECRETS_PLIST_ENV:
    candidate_paths.append(SECRETS_PLIST_ENV)

candidate_paths.extend([
    os.path.join(SRCROOT, "AniTV", "Secrets.plist"),
    os.path.join(SRCROOT, "Secrets.plist"),
])

plist_data = {}

for path in candidate_paths:
    if os.path.exists(path):
        try:
            with open(path, "rb") as f:
                plist_data = plistlib.load(f)
            print(f"[generate_secrets] Loaded secrets from {path}")
            break
        except Exception as e:
            print(f"[generate_secrets] Warning: Failed to read {path}: {e}")

# Key mapping: Dict key in plist -> Swift property name
KEYS = {
    "BangumiOAuthClientID": "bangumiOAuthClientID",
    "BangumiOAuthClientSecret": "bangumiOAuthClientSecret",
    "TMDBApiKey": "tmdbAPIKey",
    "DanDanPlayAppId": "danDanPlayAppId",
    "DanDanPlayAppSecret": "danDanPlayAppSecret",
}

# XOR Mask Key for obfuscation
XOR_KEY = 0x5A

def obfuscate_string(val: str, mask: int = XOR_KEY) -> str:
    if not val:
        return "[]"
    bytes_arr = [ord(c) ^ mask for c in val]
    return "[" + ", ".join(f"0x{b:02X}" for b in bytes_arr) + "]"

swift_properties = []
for plist_key, swift_prop in KEYS.items():
    val = plist_data.get(plist_key) or os.environ.get(plist_key, "")
    val_str = str(val).strip()
    bytes_repr = obfuscate_string(val_str, XOR_KEY)
    swift_properties.append(f"    static let {swift_prop} = deobfuscate({bytes_repr}, key: 0x{XOR_KEY:02X})")

output_path = os.path.join(SRCROOT, "AniTV", "Utils", "GeneratedSecrets.swift")
os.makedirs(os.path.dirname(output_path), exist_ok=True)

swift_code = f"""//
// GeneratedSecrets.swift
// AniTV
//
// Automatically generated by scripts/generate_secrets.py.
// DO NOT EDIT MANUALLY.
//

import Foundation

enum GeneratedSecrets {{
{chr(10).join(swift_properties)}

    private static func deobfuscate(_ cipher: [UInt8], key: UInt8) -> String {{
        guard !cipher.isEmpty else {{ return "" }}
        let bytes = cipher.map {{ $0 ^ key }}
        return String(bytes: bytes, encoding: .utf8) ?? ""
    }}
}}
"""

with open(output_path, "w", encoding="utf-8") as f:
    f.write(swift_code)

print(f"[generate_secrets] Wrote generated secrets to {output_path}")
